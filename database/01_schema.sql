BEGIN;

CREATE TABLE roles (
    id   integer               NOT NULL,
    name character varying(50) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id)
);

CREATE TABLE users (
    id                   integer GENERATED BY DEFAULT AS IDENTITY,
    login                character varying(50)  NOT NULL,
    password_hash        character varying(100) NOT NULL,
    full_name            character varying(150) NOT NULL,
    role_id              integer                NOT NULL,
    failed_login_count   integer                NOT NULL DEFAULT 0,
    is_locked            boolean                NOT NULL DEFAULT FALSE,
    must_change_password boolean                NOT NULL DEFAULT TRUE,
    created_at           timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_failed_login_count CHECK (failed_login_count >= 0),
    CONSTRAINT fk_users_roles_role_id FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE TABLE groups (
    id              integer GENERATED BY DEFAULT AS IDENTITY,
    name            character varying(20)  NOT NULL,
    specialty       character varying(150) NOT NULL,
    course          smallint               NOT NULL,
    curator_user_id integer,
    CONSTRAINT pk_groups PRIMARY KEY (id),
    CONSTRAINT ck_groups_course CHECK (course BETWEEN 1 AND 6),
    CONSTRAINT fk_groups_users_curator_user_id FOREIGN KEY (curator_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE students (
    id                 integer GENERATED BY DEFAULT AS IDENTITY,
    group_id           integer               NOT NULL,
    last_name          character varying(50) NOT NULL,
    first_name         character varying(50) NOT NULL,
    middle_name        character varying(50),
    record_book_number character varying(20) NOT NULL,
    user_id            integer,
    CONSTRAINT pk_students PRIMARY KEY (id),
    CONSTRAINT fk_students_groups_group_id FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_students_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE teachers (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    last_name   character varying(50) NOT NULL,
    first_name  character varying(50) NOT NULL,
    middle_name character varying(50),
    user_id     integer,
    CONSTRAINT pk_teachers PRIMARY KEY (id),
    CONSTRAINT fk_teachers_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE subjects (
    id   integer GENERATED BY DEFAULT AS IDENTITY,
    name character varying(150) NOT NULL,
    CONSTRAINT pk_subjects PRIMARY KEY (id)
);

CREATE TABLE lessons (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    date        date     NOT NULL,
    pair_number smallint NOT NULL,
    subject_id  integer  NOT NULL,
    teacher_id  integer  NOT NULL,
    group_id    integer  NOT NULL,
    hours       smallint NOT NULL DEFAULT 2,
    CONSTRAINT pk_lessons PRIMARY KEY (id),
    CONSTRAINT ck_lessons_hours CHECK (hours > 0),
    CONSTRAINT ck_lessons_pair_number CHECK (pair_number BETWEEN 1 AND 7),
    CONSTRAINT fk_lessons_groups_group_id FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lessons_subjects_subject_id FOREIGN KEY (subject_id) REFERENCES subjects (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lessons_teachers_teacher_id FOREIGN KEY (teacher_id) REFERENCES teachers (id) ON DELETE RESTRICT
);

CREATE TABLE excuse_documents (
    id                    integer GENERATED BY DEFAULT AS IDENTITY,
    student_id            integer               NOT NULL,
    type                  character varying(30) NOT NULL,
    number                character varying(50) NOT NULL,
    issue_date            date                  NOT NULL,
    valid_from            date                  NOT NULL,
    valid_to              date                  NOT NULL,
    status                character varying(20) NOT NULL,
    registered_by_user_id integer               NOT NULL,
    registered_at         timestamp with time zone NOT NULL DEFAULT (now()),
    reviewed_by_user_id   integer,
    reviewed_at           timestamp with time zone,
    review_comment        character varying(500),
    CONSTRAINT pk_excuse_documents PRIMARY KEY (id),
    CONSTRAINT ck_excuse_documents_period CHECK (valid_to >= valid_from),
    CONSTRAINT ck_excuse_documents_status CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    CONSTRAINT ck_excuse_documents_type CHECK (type IN ('MedicalCertificate', 'Order', 'Statement')),
    CONSTRAINT fk_excuse_documents_students_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE RESTRICT,
    CONSTRAINT fk_excuse_documents_users_registered_by_user_id FOREIGN KEY (registered_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_excuse_documents_users_reviewed_by_user_id FOREIGN KEY (reviewed_by_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE absences (
    id                 integer GENERATED BY DEFAULT AS IDENTITY,
    student_id         integer               NOT NULL,
    lesson_id          integer               NOT NULL,
    status             character varying(20) NOT NULL,
    marked_by_user_id  integer               NOT NULL,
    marked_at          timestamp with time zone NOT NULL DEFAULT (now()),
    excuse_document_id integer,
    CONSTRAINT pk_absences PRIMARY KEY (id),
    CONSTRAINT ck_absences_status CHECK (status IN ('Unexcused', 'Excused')),
    CONSTRAINT fk_absences_excuse_documents_excuse_document_id FOREIGN KEY (excuse_document_id) REFERENCES excuse_documents (id) ON DELETE SET NULL,
    CONSTRAINT fk_absences_lessons_lesson_id FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT fk_absences_students_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE RESTRICT,
    CONSTRAINT fk_absences_users_marked_by_user_id FOREIGN KEY (marked_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE notifications (
    id         integer GENERATED BY DEFAULT AS IDENTITY,
    user_id    integer                NOT NULL,
    student_id integer,
    message    character varying(500) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    is_read    boolean                NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_students_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE audit_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id    integer,
    action     character varying(10) NOT NULL,
    table_name character varying(63) NOT NULL,
    record_id  bigint,
    changed_at timestamp with time zone NOT NULL DEFAULT (now()),
    old_values jsonb,
    new_values jsonb,
    CONSTRAINT pk_audit_log PRIMARY KEY (id),
    CONSTRAINT ck_audit_log_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT fk_audit_log_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX ix_roles_name ON roles (name);
CREATE UNIQUE INDEX ix_users_login ON users (login);
CREATE INDEX ix_users_role_id ON users (role_id);
CREATE UNIQUE INDEX ix_groups_name ON groups (name);
CREATE INDEX ix_groups_curator_user_id ON groups (curator_user_id);
CREATE INDEX ix_students_group_id ON students (group_id);
CREATE UNIQUE INDEX ix_students_record_book_number ON students (record_book_number);
CREATE UNIQUE INDEX ix_students_user_id ON students (user_id);
CREATE UNIQUE INDEX ix_teachers_user_id ON teachers (user_id);
CREATE UNIQUE INDEX ix_subjects_name ON subjects (name);

CREATE UNIQUE INDEX ix_lessons_group_id_date_pair_number ON lessons (group_id, date, pair_number);
CREATE INDEX ix_lessons_teacher_id_date ON lessons (teacher_id, date);
CREATE INDEX ix_lessons_subject_id ON lessons (subject_id);

CREATE UNIQUE INDEX ix_absences_student_id_lesson_id ON absences (student_id, lesson_id);
CREATE INDEX ix_absences_lesson_id ON absences (lesson_id);
CREATE INDEX ix_absences_marked_by_user_id ON absences (marked_by_user_id);
CREATE INDEX ix_absences_excuse_document_id ON absences (excuse_document_id);

CREATE INDEX ix_excuse_documents_student_id_valid_from_valid_to ON excuse_documents (student_id, valid_from, valid_to);
CREATE INDEX ix_excuse_documents_status ON excuse_documents (status);
CREATE INDEX ix_excuse_documents_registered_by_user_id ON excuse_documents (registered_by_user_id);
CREATE INDEX ix_excuse_documents_reviewed_by_user_id ON excuse_documents (reviewed_by_user_id);

CREATE INDEX ix_notifications_user_id_is_read ON notifications (user_id, is_read);
CREATE INDEX ix_notifications_student_id ON notifications (student_id);

CREATE INDEX ix_audit_log_changed_at ON audit_log (changed_at);
CREATE INDEX ix_audit_log_table_name_record_id ON audit_log (table_name, record_id);
CREATE INDEX ix_audit_log_user_id ON audit_log (user_id);

INSERT INTO roles (id, name) VALUES
    (1, 'Администратор'),
    (2, 'Куратор'),
    (3, 'Преподаватель'),
    (4, 'Староста'),
    (5, 'Студент');

COMMIT;
